/**
 * delete the appointment currently selected in the table.
 * @param evt the action event
 */
    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        // TODO add your handling code here:
        int selectedRow = appointmentsTable.getSelectedRow();
    
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a slot from the table first!");
        return;
    }
    String dateStr = appointmentsTable.getValueAt(selectedRow, 0).toString();
    String timeStr = appointmentsTable.getValueAt(selectedRow, 1).toString();
     LocalDate date = LocalDate.parse(dateStr);
    LocalTime time = LocalTime.parse(timeStr);
    Appointment toDelete = new Appointment(date, time);
        appointmentManager.removeSlot(toDelete);
JOptionPane.showMessageDialog(this, "Slot deleted successfully.");
    refreshTable();
    }//GEN-LAST:event_deleteBtnActionPerformed

