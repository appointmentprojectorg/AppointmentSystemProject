/**
 * get data from manager and fill the table.
 */
   private void refreshTable() {
    DefaultTableModel model = (DefaultTableModel) appointmentsTable.getModel();
    model.setRowCount(0); 

    java.util.List<soft.appointment.domain.Appointment> list = appointmentManager.getAvailableSlots();

    for (soft.appointment.domain.Appointment a : list) {
        model.addRow(new Object[]{
            a.getDate(), 
            a.getStartTime(), 
            a.isAvailable() ? "Available" : "Booked"
        });
    }
}
   /**
 * Sets the welcome message with a safety check for long names.
 * @param username the name to display
 */
private void setSafeWelcomeMessage(String username) {
    String displayName = username;
    
    if (username.length() > 15) {
        displayName = username.substring(0, 12) + "...";
    }
    
    welcomeLabel.setText("Hello, " + displayName);
}
